export function findLocalTip(location) {
  if (!location) return null;
  const countryCode = String(location.countryCode || "").toUpperCase();
  if (!/^[A-Z]{2}$/.test(countryCode)) return null;

  const cityKey = normalizeKey(location.city);
  const cityTips = LOCAL_TIPS.cities[countryCode];
  if (cityKey && cityTips) {
    if (cityTips[cityKey]) return cityTips[cityKey];
    const nearMatch = Object.entries(cityTips).find(
      ([key]) => cityKey.startsWith(`${key} `) || key.startsWith(`${cityKey} `),
    );
    if (nearMatch) return nearMatch[1];
  }

  return LOCAL_TIPS.countries[countryCode] || null;
}

export function normalizeKey(value) {
  return String(value || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}
